/** 标签展示名：优先中文映射，未知标签回退为可读英文 */
export function tagLabel(tagId: string): string {
  const key = tagId.replace(/^minecraft:/, '')
  const zh = TAG_ZH[key]
  if (zh) return zh
  return key
    .split('/')
    .map((part) =>
      part
        .split('_')
        .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
        .join(' '),
    )
    .join(' / ')
}
